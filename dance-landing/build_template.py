def list_sheet(title, headers, widths, examples, note, dropdowns=None, rows=40):
    s = wb.create_sheet(title)
    s.cell(row=1, column=1, value=note).font = Font(bold=True, size=10, color=ACCENT)
    s.cell(row=1, column=1).alignment = Alignment(vertical="center", wrap_text=True)
    s.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    s.row_dimensions[1].height = 30
    s.append(headers)
    style_header(s, row=2, ncols=len(headers))
    set_widths(s, widths)
    r = 3
    for ex in examples:
        for i, v in enumerate(ex, start=1):
            c = s.cell(row=r, column=i, value=v)
            c.fill = fill_example
            c.font = Font(size=9, color="7A6A2F")
            c.alignment = Alignment(vertical="top", wrap_text=True)
            c.border = box
        s.row_dimensions[r].height = 34
        r += 1
    for _ in range(rows):
        for i in range(1, len(headers) + 1):
            c = s.cell(row=r, column=i)
            c.border = box
            c.alignment = Alignment(vertical="top", wrap_text=True)
            c.font = Font(size=10)
        s.row_dimensions[r].height = 30
        r += 1
    s.freeze_panes = "A3"
    s.auto_filter.ref = f"A2:{get_column_letter(len(headers))}{r-1}"
    if dropdowns:
        for col_letter, values in dropdowns.items():
            dv = DataValidation(type="list", formula1='"%s"' % ",".join(values), allow_blank=True)
            s.add_data_validation(dv)
            dv.add(f"{col_letter}3:{col_letter}{r-1}")
    return s

